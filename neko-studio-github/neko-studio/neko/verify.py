"""Place matching. Stock search engines rank by keyword relevance, not geography,
so every result is scored against the place name and labelled:

- fiable      the full place name appears in the media's own title/description
- à vérifier  only part of the name appears; a human must confirm
- écarté      generic match (country only, nothing) or likely synthetic media
"""
from __future__ import annotations

import re
import unicodedata

from .models import REJECTED, RELIABLE, TO_CHECK, MediaItem

# French country names -> English, since media titles are mostly in English.
COUNTRIES = {
    "japon": "japan", "chine": "china", "coree": "korea", "coree du sud": "south korea",
    "thailande": "thailand", "vietnam": "vietnam", "indonesie": "indonesia", "inde": "india",
    "italie": "italy", "espagne": "spain", "allemagne": "germany", "grece": "greece",
    "royaume uni": "united kingdom", "angleterre": "england", "ecosse": "scotland",
    "irlande": "ireland", "suisse": "switzerland", "autriche": "austria", "belgique": "belgium",
    "pays bas": "netherlands", "norvege": "norway", "suede": "sweden", "danemark": "denmark",
    "islande": "iceland", "croatie": "croatia", "turquie": "turkey", "maroc": "morocco",
    "egypte": "egypt", "perou": "peru", "bresil": "brazil", "mexique": "mexico",
    "etats unis": "united states", "canada": "canada", "australie": "australia",
    "nouvelle zelande": "new zealand", "france": "france", "portugal": "portugal",
    "cambodge": "cambodia", "nepal": "nepal", "sri lanka": "sri lanka", "taiwan": "taiwan",
}

# Words that say nothing about *which* place it is.
GENERIC = {
    "village", "town", "city", "temple", "shrine", "restaurant", "mountain", "lake", "river",
    "beach", "park", "trail", "hike", "randonnee", "lac", "ville", "plage", "montagne",
    "the", "de", "du", "la", "le", "les", "des", "of", "and", "et", "san", "saint", "st",
}

SYNTHETIC = ("ai generated", "ai-generated", "generated by", "midjourney", "stable diffusion",
             "dall e", "3d render", "rendering", "illustration", "cgi", "digital art")

NOT_A_VIEW = ("locmap", "location map", "map of", "diagram", "logo", "coat of arms", "flag of",
              "manhole", "emblem", "seal of", "stamp", "portrait of", "emaki", "scroll", "woodblock",
              "ukiyo e", "painting", "screenshot")

# Words in a media's name that signal a strong, representative view, or a minor detail.
STRIKING = ("view", "panorama", "panoramic", "aerial", "drone", "overview", "from above", "skyline",
            "landscape", "sunset", "sunrise", "snow", "autumn", "night", "illumination", "lake", "mountain",
            "mountains", "valley", "coast", "bay", "village", "old town", "temple", "castle", "vue")
MINOR = ("sign", "signboard", "plaque", "detail", "interior", "museum", "inscription", "door", "window",
         "grave", "tomb", "statue", "bus", "parking", "toilet", "menu", "ticket", "souvenir", "shop",
         "pension", "hotel", "label", "notice", "board", "facade", "exterior", "building", "office", "station")
# News and events: never a travel opener, whatever place they mention.
EVENTS = ("pavilion", "conference", "summit", "minister", "president", "prime", "press", "interview",
          "speech", "meeting", "expo", "forum", "cop", "cop28", "election", "protest", "ceremony", "visit",
          "delegation", "startup", "company", "logo", "award")
SCENIC = ("landscape", "mountain", "mountains", "lake", "valley", "coast", "panorama", "autumn", "snow",
          "sunrise", "sunset", "temple", "shrine", "forest", "river", "rice", "terraces", "fuji", "village")

MIN_SHORT_SIDE = 720  # pixels; below that a 1080x1920 frame looks blurry


def normalize(text: str) -> str:
    text = unicodedata.normalize("NFKD", text or "").encode("ascii", "ignore").decode()
    text = re.sub(r"[^a-z0-9]+", " ", text.lower())
    return f" {text.strip()} "


def parse_place(query: str) -> tuple[str, str]:
    """'Shirakawa-go, Japon' -> ('Shirakawa-go', 'japan')."""
    main, _, rest = query.partition(",")
    country = normalize(rest).strip()
    return main.strip(), COUNTRIES.get(country, country)


def search_queries(query: str) -> list[str]:
    main, country = parse_place(query)
    queries = [main]
    if country:
        queries.append(f"{main} {country}")
    joined = main.replace("-", "")
    if joined != main:
        queries.append(joined)
    return list(dict.fromkeys(q for q in queries if q))


def _unusable(item: MediaItem, text: str) -> str:
    """Why a media can never go in a reel, or '' if it can."""
    if any(s in text for s in (normalize(x) for x in SYNTHETIC)):
        return "semble être une image de synthèse ou une illustration"
    if any(s in text for s in (normalize(x) for x in NOT_A_VIEW)):
        return "carte, schéma, logo ou document, pas une prise de vue"
    if max(item.width, item.height) and min(item.width, item.height) < MIN_SHORT_SIDE:
        return f"résolution trop faible ({item.width}×{item.height})"
    return ""


def appeal(item: MediaItem) -> float:
    """How striking and representative a media is likely to be, about -0.5..1.
    Uses the media's own name only: category lists mention everything."""
    name = normalize(item.title.split(".")[0])
    value = 0.5 * item.quality
    value += min(0.3, 0.15 * sum(f" {w} " in name for w in STRIKING))
    value -= 0.3 * any(f" {w} " in name for w in MINOR)
    if 0 < item.year < 2008:
        value -= 0.25  # old scans and early digital photos look dull next to recent footage
    return value


def score(item: MediaItem, query: str) -> MediaItem:
    main, country = parse_place(query)
    phrase = normalize(main)
    text = normalize(item.title)
    squashed_phrase = phrase.replace(" ", "")
    squashed_text = text.replace(" ", "")
    distinctive = [t for t in phrase.split() if len(t) >= 4 and t not in GENERIC]
    item.reasons = []

    reason = _unusable(item, text)
    if reason:
        item.status, item.score = REJECTED, 0.0
        item.reasons.append(reason)
        return item

    if phrase.strip() and (phrase in text or squashed_phrase in squashed_text):
        item.status, item.score = RELIABLE, 1.0
        item.reasons.append(f"le titre contient « {main} »")
    elif distinctive and any(f" {t} " in text for t in distinctive):
        found = [t for t in distinctive if f" {t} " in text]
        item.status, item.score = TO_CHECK, 0.5
        item.reasons.append(f"seulement une partie du nom trouvée : {', '.join(found)}")
    else:
        item.status, item.score = REJECTED, 0.1 if country and f" {country} " in text else 0.0
        item.reasons.append("aucune mention du lieu (résultat générique)")
        return item

    # Ranking among usable media: real footage first, then beauty and representativeness.
    if item.kind == "video":
        item.score += 0.3
    if item.is_portrait:
        item.score += 0.1
    if country and f" {country} " in text:
        item.score += 0.05
    item.score += appeal(item)
    return item


def score_country(item: MediaItem, country: str) -> MediaItem:
    """Opening shots: must name the country and be a striking wide view, never a detail."""
    text = normalize(item.title)
    name = normalize(item.title.split(".")[0])
    item.reasons, item.role = [], "country"
    reason = _unusable(item, text)
    if reason or f" {country} " not in text:
        item.status, item.score = REJECTED, 0.0
        item.reasons.append(reason or f"ne mentionne pas « {country} »")
        return item
    if not any(f" {w} " in name for w in STRIKING) or any(f" {w} " in name for w in MINOR + EVENTS):
        item.status, item.score = REJECTED, 0.0
        item.reasons.append("pas une vue large et représentative du pays")
        return item
    item.status = RELIABLE
    # Travel openers: nature and heritage set the mood better than city streets.
    scenic = 0.25 * any(f" {w} " in name for w in SCENIC)
    item.score = 0.3 * (item.kind == "video") + appeal(item) + scenic
    item.reasons.append(f"vue de {country} pour l'ouverture")
    return item
