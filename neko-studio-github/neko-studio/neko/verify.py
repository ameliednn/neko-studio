def confirm_by_neighbours(items: list[MediaItem], query: str) -> None:
    """Second pass for short, ambiguous names. Media confirmed by the country also name the
    area around ("Ine Town, Yosa District, Kyoto"): those local words then confirm the other
    media mentioning the name. An unrelated "Ine Aho festival" shares none and stays out."""
    q = parse_query(query)
    sure = [i for i in items if i.status == RELIABLE]
    unsure = [i for i in items if i.status == TO_CHECK and i.reasons and i.reasons[0].endswith(f"de {q.country}")]
    if not sure or not unsure:
        return
    name = set(normalize(q.core or q.main).split())
    anchors: set[str] = set()
    for i in sure:
        # Proper nouns (capitalised words) from the media's own name only, never from the
        # catalogue's housekeeping categories ("Files by…"): place names, not "traditional".
        own_name = re.split(r"\.(?:jpe?g|png|webp|webm|ogv|mp4|tiff?)\b", i.title, flags=re.I)[0]
        proper = {normalize(w).strip() for w in re.findall(r"\b[A-Z][A-Za-z\-]{3,}", own_name)}
        anchors |= {w for w in proper if w and " " not in w and w not in COMMON and w not in name
                    and w != q.country and w not in {"japanese", "traditional", "festival", "file"}}
    for i in unsure:
        shared = sorted(w for w in set(normalize(i.title).split()) if w in anchors)
        if shared:
            i.status, i.score = RELIABLE, 1.0 + 0.3 * (i.kind == "video") + appeal(i)
            i.reasons = [f"« {q.core or q.main} » + lieux voisins : {', '.join(shared[:3])}"]


def score_country(item: MediaItem, country: str) -> MediaItem:
    """Opening shots: must name the country and be a striking wide view, never a detail."""
    text = normalize(item.title)
    name = normalize(item.title.split(".")[0])
    item.reasons, item.role = [], "country"
    reason = _unusable(item, text)
    if reason or f" {country} " not in text:
        item.status, item.score = REJECTED, 0.0
        item.reasons.append(reason or f"ne mentionne pas « {country} »")
        return item
    if not any(f" {w} " in name for w in STRIKING) or any(f" {w} " in name for w in MINOR + EVENTS):
        item.status, item.score = REJECTED, 0.0
        item.reasons.append("pas une vue large et représentative du pays")
        return item
    item.status = RELIABLE
    # Travel openers: nature and heritage set the mood better than city streets.
    scenic = 0.25 * any(f" {w} " in name for w in SCENIC)
    item.score = 0.3 * (item.kind == "video") + appeal(item) + scenic
    item.reasons.append(f"vue de {country} pour l'ouverture")
    return item
